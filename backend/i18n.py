def current_language() -> str:
    """Return the active language code from settings, defaulting to 'en'."""
    try:
        from backend import config as cfg
        lang = str(cfg.get_settings().get("language", "en") or "en").strip().lower()
        return "zh" if lang.startswith("zh") else "en"
    except Exception:
        return "en"


def get_text(key: str, lang: str = "en", **kwargs: Any) -> str:
    """Return the localized string for `key` in `lang` (defaulting to 'en')."""
    normalized_lang = "zh" if str(lang or "en").lower().startswith("zh") else "en"
    template = TRANSLATIONS.get(normalized_lang, {}).get(
        key,
        TRANSLATIONS["en"].get(key, key),
    )
    if kwargs:
        try:
            return template.format(**kwargs)
        except Exception:
            return template
    return template


def t(key: str, lang: Optional[str] = None, **kwargs: Any) -> str:
    """Return the localized string using the current configured language if `lang` is omitted."""
    resolved = current_language() if lang is None else lang
    return get_text(key, resolved, **kwargs)
