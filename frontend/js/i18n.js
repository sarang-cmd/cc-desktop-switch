  function normalizeLanguage(value) {
    const tag = String(value || "").trim().toLowerCase();
    if (tag.startsWith("zh")) return "zh";
    if (tag.startsWith("en")) return "en";
    return "";
  }

  function storedLanguage() {
    try {
      return normalizeLanguage(localStorage.getItem(STORAGE_KEY));
    } catch (error) {
      return "";
    }
  }

  // English is the default on first launch. The OS locale is deliberately ignored;
  // only an explicit user choice (persisted in localStorage or settings.language)
  // switches the interface language.
  let currentLanguage = storedLanguage() || "en";

  function t(key, lang = currentLanguage) {
    const activeDict = dictionaries[lang] || dictionaries.en;
    return activeDict[key] || dictionaries.en[key] || dictionaries.zh[key] || key;
  }

  function apply(language, options = {}) {
    const { persist = true } = options;
    currentLanguage = normalizeLanguage(language) || "en";
    if (persist) {
      try {
        localStorage.setItem(STORAGE_KEY, currentLanguage);
      } catch (error) {
        // Ignore storage write errors
      }
    }
    document.documentElement.lang = currentLanguage === "zh" ? "zh-CN" : "en";
    document.querySelectorAll("[data-i18n]").forEach((node) => {
      node.textContent = t(node.dataset.i18n);
    });
    document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
      node.setAttribute("placeholder", t(node.dataset.i18nPlaceholder));
    });
    document.querySelectorAll("[data-i18n-title]").forEach((node) => {
      node.setAttribute("title", t(node.dataset.i18nTitle));
    });
    document.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
      node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
    });
    document.querySelectorAll("[data-lang]").forEach((node) => {
      const isActive = node.dataset.lang === currentLanguage;
      node.classList.toggle("active", isActive);
      node.setAttribute("aria-pressed", isActive ? "true" : "false");
    });
    window.dispatchEvent(new CustomEvent("cc:i18n", { detail: { language: currentLanguage } }));
  }

